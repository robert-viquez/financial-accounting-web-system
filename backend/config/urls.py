from django.contrib import admin
from django.urls import path
from django.urls import include, path
from django.conf import settings
from django.conf.urls.static import static
from rest_framework_simplejwt.views import (
    TokenObtainPairView,
    TokenRefreshView,
)
from drf_spectacular.views import SpectacularAPIView, SpectacularSwaggerView

admin.site.site_header = "Administración del ERP"
admin.site.site_title = "Sitio administrativo"
admin.site.index_title = "Sitio administrativo"

urlpatterns = [
    path('admin/', admin.site.urls),
    # Auth API
    path("api/token/", TokenObtainPairView.as_view(), name="token_obtain_pair"),
    path("api/token/refresh/", TokenRefreshView.as_view(), name="token_refresh"),
    path("api/", include("terceros.urls")),
    path("api/", include("inventario.urls")),
    path("api/", include("ventas.urls")),
    path("api/", include("compras.urls")),
    path("api/", include("finanzas.urls")),
    path("api/", include("contabilidad.urls")),
    path("api/", include("usuarios.urls")),
    path("api/schema/", SpectacularAPIView.as_view(), name="schema"),
    path("api/docs/", SpectacularSwaggerView.as_view(url_name="schema"), name="swagger-ui"),
]

if settings.DEBUG:
    urlpatterns += static(settings.MEDIA_URL, document_root=settings.MEDIA_ROOT)
